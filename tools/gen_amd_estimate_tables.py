"""Writes src/runtime_fp_amd.h: shadPS4's AMD rcpps/rsqrtps tables for NHL 19 "Overtime online".

Overtime's shadPS4 players on Intel CPUs run every (v)rcpps / (v)rsqrtps as the CPU's own estimate
XOR a delta that turns it into AMD's result (shadPS4 src/core/cpu_patches.cpp,
GenerateReciprocalInstruction): delta = xor_values[index_table[input >> 11]]. On AMD CPUs the
instructions stay native. The port's Overtime online mode does the same (src/runtime_fp.c), with the
same tables, read here from a shadPS4 checkout (GPL-2.0-or-later, like this file):

  src/resources/amd_rcp_index_table.bin.zstd, amd_rsqrt_index_table.bin.zstd  (2^21 bytes each)
  src/core/cpu_patches.cpp: rcp_xor_values, rsqrt_xor_values

Each index table is 512 blocks of 4096 entries (one per sign and exponent) and has only a few
distinct blocks, so the header keeps the distinct blocks and a block map (2^21 bytes at run time).
Needs the zstd command. Usage:

  python3 tools/gen_amd_estimate_tables.py SHADPS4_DIR [--ref COMMIT] [--out src/runtime_fp_amd.h]
"""
import argparse
import hashlib
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TABLE = 1 << 21
BLOCK = 4096
NAMES = {'rcp': 'amd_rcp_index_table.bin.zstd', 'rsqrt': 'amd_rsqrt_index_table.bin.zstd'}


def read(shadps4, ref, path):
    if ref:
        return subprocess.run(['git', '-C', str(shadps4), 'show', f'{ref}:{path}'], check=True, capture_output=True).stdout
    return (shadps4 / path).read_bytes()


def decompress(data):
    try:
        out = subprocess.run(['zstd', '-d', '-c', '-q'], input=data, check=True, capture_output=True).stdout
    except FileNotFoundError:
        sys.exit('gen_amd_estimate_tables: needs the zstd command')
    if len(out) != TABLE:
        sys.exit(f'gen_amd_estimate_tables: a table decompressed to {len(out)} bytes, not {TABLE}')
    return out


def xor_values(source, name):
    m = re.search(name + r'\s*=\s*\{([^}]*)\}', source)
    if not m:
        sys.exit(f'gen_amd_estimate_tables: {name} not found in cpu_patches.cpp')
    return [int(v, 16) for v in re.findall(r'0x[0-9a-fA-F]+', m.group(1))]


def c_string(text, width=96, indent='    '):
    return '\n'.join(f'{indent}"{text[i:i + width]}"' for i in range(0, len(text), width))


def table_part(kind, table, values):
    if max(table) >= len(values):
        sys.exit(f'gen_amd_estimate_tables: {kind} index {max(table)} past its {len(values)} xor values')
    zero = bytes(BLOCK)
    blocks = [zero]  # block 'A' is always the all-zero one (stored as NULL)
    order = []
    for i in range(0, TABLE, BLOCK):
        block = table[i:i + BLOCK]
        if block not in blocks:
            blocks.append(block)
        order.append(blocks.index(block))
    if len(blocks) > 26:
        sys.exit(f'gen_amd_estimate_tables: {kind} has {len(blocks)} distinct blocks')
    lines = [f'static const uint32_t amd_{kind}_xor[{len(values)}] = {{' + ', '.join(f'0x{v:08x}' for v in values) + '};',
             f'static const char amd_{kind}_map[{TABLE // BLOCK + 1}] =',
             c_string(''.join(chr(65 + b) for b in order), 64) + ';',
             f'static const char *const amd_{kind}_blocks[{len(blocks)}] = {{', '    NULL,']
    for block in blocks[1:]:
        lines.append(c_string(''.join(chr(65 + v) for v in block)) + ',')
    lines.append('};')
    lines.append(f'#define AMD_{kind.upper()}_TABLE_SHA256 "{hashlib.sha256(table).hexdigest()}"')
    return '\n'.join(lines)


def main():
    p = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    p.add_argument('shadps4', type=Path, help='a shadPS4 source checkout')
    p.add_argument('--ref', help='read the files at this git commit of the checkout (default: the files on disk)')
    p.add_argument('--out', type=Path, default=ROOT / 'src/runtime_fp_amd.h')
    a = p.parse_args()
    commit = a.ref
    if commit:
        commit = subprocess.run(['git', '-C', str(a.shadps4), 'rev-parse', commit], check=True, capture_output=True,
                                text=True).stdout.strip()
    source = read(a.shadps4, commit, 'src/core/cpu_patches.cpp').decode('utf-8')
    packed = {kind: read(a.shadps4, commit, f'src/resources/{name}') for kind, name in NAMES.items()}
    values = {'rcp': xor_values(source, 'rcp_xor_values'), 'rsqrt': xor_values(source, 'rsqrt_xor_values')}
    origin = f'commit {commit}' if commit else 'a checkout'
    head = [
        '/* SPDX-License-Identifier: GPL-2.0-or-later',
        ' * Generated by tools/gen_amd_estimate_tables.py; do not edit.',
        ' *',
        ' * shadPS4\'s AMD rcpps/rsqrtps tables (github.com/shadps4-emu/shadPS4, GPL-2.0-or-later; added in',
        f' * PR #5241), from {origin}:',
    ]
    for kind, name in NAMES.items():
        head.append(f' *   src/resources/{name} (sha256 {hashlib.sha256(packed[kind]).hexdigest()})')
    head += [
        ' *   src/core/cpu_patches.cpp rcp_xor_values, rsqrt_xor_values',
        ' * An index table has 2^21 entries, one per input >> 11: entry i is character i & 4095 of block',
        ' * map[i >> 12], minus \'A\'; block \'A\' (NULL) is all zeros. AMD_*_TABLE_SHA256 is the expanded',
        ' * table\'s, equal to the decompressed resource\'s. */',
        '#pragma once',
        '#include <stddef.h>',
        '#include <stdint.h>',
        '',
    ]
    parts = [table_part(kind, decompress(packed[kind]), values[kind]) for kind in NAMES]
    a.out.write_text('\n'.join(head) + '\n\n'.join(parts) + '\n', encoding='ascii', newline='\n')
    print(f'gen_amd_estimate_tables: wrote {a.out}')


if __name__ == '__main__':
    main()
